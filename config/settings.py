# Database: PostgreSQL by default, with an automatic SQLite fallback.
# USE_SQLITE=True forces SQLite. Otherwise we probe the Postgres port and fall back
# to SQLite if nothing is listening (e.g. Docker is not running).
def postgres_reachable(host, port, timeout=1.0):
    try:
        with socket.create_connection((host, port), timeout=timeout):
            return True
    except OSError:
        return False


DB_HOST = os.environ.get("POSTGRES_HOST", "localhost")
DB_PORT = int(os.environ.get("POSTGRES_PORT", "5432"))

if env_bool("USE_SQLITE", False):
    USE_POSTGRES = False
elif postgres_reachable(DB_HOST, DB_PORT):
    USE_POSTGRES = True
else:
    USE_POSTGRES = False
    warnings.warn(f"PostgreSQL not reachable at {DB_HOST}:{DB_PORT}; falling back to SQLite.", stacklevel=2)

if USE_POSTGRES:
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.postgresql",
            "NAME": os.environ.get("POSTGRES_DB", "po_system"),
            "USER": os.environ.get("POSTGRES_USER", "po_user"),
            "PASSWORD": os.environ.get("POSTGRES_PASSWORD", "po_password"),
            "HOST": DB_HOST,
            "PORT": DB_PORT,
        }
    }
else:
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": BASE_DIR / "db.sqlite3",
        }
    }

